// Helper function to get service by slug or id
export function getServiceBySlug(slug) {
  if (!slug) return null
  const normalized = slug.toLowerCase()
  return servicesData.find(
    s => s.slug.toLowerCase() === normalized || s.id.toLowerCase() === normalized
  )
}
